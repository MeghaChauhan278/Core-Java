public class J04_Arithemetic {
    public static void main(String args[]){

        //order of operation [P-E-M-D-A-S]
        int x=10;
        int y=6;
        x=x+y;
        //or (Augmented Assignment operator)
        x+=y;
        System.out.println(x);


        //Increment and DEcrement operator
        int z=1;
        z=z+1; //or  z+=1 or z++
        z=z-1; //or z-=1 or z--
        System.out.println(z);

    }
    
}
